#!/usr/bin/env node
// FR-NRM-6: the routing spelling vocabulary is a VERSIONED, COMMITTED artifact generated from the registry's own example phrases, so a change to the
// examples cannot silently change routing. Regenerate with `node scripts/ask-routing-vocabulary.js --write`; tests/ask/routingNormalization.test.js fails when stale.
const fs = require('node:fs'); const path = require('node:path'); const crypto = require('node:crypto');
const BACKEND = path.resolve(__dirname, '..');
process.env.TS_NODE_TRANSPILE_ONLY = process.env.TS_NODE_TRANSPILE_ONLY || 'true';
process.env.TS_NODE_PROJECT = process.env.TS_NODE_PROJECT || path.join(BACKEND, 'tsconfig.test-cache.json');
require(path.join(BACKEND, 'node_modules/ts-node/register'));
const { ASK_OPERATION_DEFINITIONS } = require(path.join(BACKEND, 'src/services/ask/askOperationRegistry.ts'));
const OUT = path.join(BACKEND, 'src/services/ask/support/routingVocabulary.generated.ts');

function build() {
  const counts = new Map();
  const add = (text) => { if (typeof text !== 'string') return; for (const w of text.toLowerCase().match(/[a-z]{4,}/g) ?? []) counts.set(w, (counts.get(w) ?? 0) + 1); };
  for (const d of Object.values(ASK_OPERATION_DEFINITIONS)) for (const pack of Object.values(d.semantic.languagePacks ?? {})) {
    if (!pack) continue; add(pack.intentDescription); for (const j of pack.supportedJobs ?? []) add(j); for (const e of pack.positiveExamples ?? []) add(e);
  }
  const entries = [...counts.entries()].filter(([, c]) => c >= 2).sort((a, b) => (b[1] - a[1]) || a[0].localeCompare(b[0]));
  const body = entries.map(([w, c]) => `${JSON.stringify(w)}:${c}`).join(',');
  const version = crypto.createHash('sha256').update(body).digest('hex').slice(0, 12);
  return { entries, version, body };
}
const { entries, version, body } = build();
const source = `// GENERATED by scripts/ask-routing-vocabulary.js — do not edit. FR-NRM-6 (reliability FRD): the vocabulary the routing spelling corrector may move a word toward.
// Words that occur at least twice in the registry's own example phrases, with their counts. Version ${version}.
export const ROUTING_VOCABULARY_VERSION = ${JSON.stringify(version)};
export const ROUTING_VOCABULARY: Readonly<Record<string, number>> = Object.freeze({${body}});
`;
if (process.argv.includes('--write')) { fs.writeFileSync(OUT, source); console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${entries.length} words, version ${version}`); }
else if (process.argv.includes('--check')) { const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''; console.log(cur === source ? `up to date (${version})` : 'STALE'); process.exit(cur === source ? 0 : 1); }
else console.log(`${entries.length} words, version ${version}`);
