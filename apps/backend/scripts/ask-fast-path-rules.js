#!/usr/bin/env node
// FR-FAST-1 / FR-FAST-2 / FR-FAST-9: per-rule identity for the deterministic router. Every `return resolved('OP', confidence, 'DET_OP_NN')` site in resolveAskOperation is ONE rule. The id is stable (written into the
// source once, never renumbered), and the rule's HASH covers exactly what can change its behaviour: the guarding condition, the returned operation and confidence, and the declarations the condition references
// (module-level patterns and helper functions, followed through imports). Editing one pattern changes the hash of the rules that use it and of no others. Hashes live in the generated manifest, not in the source.
//   node scripts/ask-fast-path-rules.js          check: exits 1 if the source ids or the manifests are out of date
//   node scripts/ask-fast-path-rules.js --write  assign ids to new rule sites and rewrite both generated manifests
require('ts-node/register/transpile-only');
const fs = require('node:fs'); const path = require('node:path');
const { analyze, REGISTRY, askDir } = require('./lib/askFastPathRuleScan');
const OUT_RULES = path.join(askDir, 'fastPath/ruleManifest.generated.ts');
const OUT_ADJ = path.join(askDir, 'fastPath/adjacencyManifest.generated.ts');
const write = process.argv.includes('--write');

// ---- 1. ids: keep the ones already in the source, give every new site the next number of its operation --------------------------------------------------------------------------------------------------------------------
let source = fs.readFileSync(REGISTRY, 'utf8');
let rules = analyze(source);
if (rules.some((r) => !r.operationId)) { console.error('a rule site returns a non-literal operation; split it so each rule names exactly one operation'); process.exit(2); }
const taken = new Map();
for (const r of rules) { const m = r.id && /^DET_([A-Z0-9_]+)_(\d+)$/.exec(r.id); if (m) taken.set(m[1], Math.max(taken.get(m[1]) ?? 0, Number(m[2]))); }
const edits = [];
for (const r of rules) {
  if (r.id) continue;
  const next = (taken.get(r.operationId) ?? 0) + 1; taken.set(r.operationId, next);
  edits.push({ at: r.call.arguments[r.call.arguments.length - 1].end, text: `, 'DET_${r.operationId}_${String(next).padStart(2, '0')}'` });
}
if (edits.length) {
  if (!write) { console.error(`${edits.length} rule site(s) have no id: run node scripts/ask-fast-path-rules.js --write`); process.exit(1); }
  for (const e of edits.sort((a, b) => b.at - a.at)) source = source.slice(0, e.at) + e.text + source.slice(e.at);
  fs.writeFileSync(REGISTRY, source); rules = analyze(source);
}
const manifestRules = rules.map(({ id, operationId, confidence, order, hash, condition, references }) => ({ id, operationId, confidence, order, hash, condition, references }));
const ids = manifestRules.map((r) => r.id); if (new Set(ids).size !== ids.length) { console.error('duplicate rule ids: ' + ids.filter((x, i) => ids.indexOf(x) !== i).join(', ')); process.exit(2); }
const rules_ = manifestRules;

// ---- 4. the operation-owned adjacency manifest (FR-FAST-9): the operation that resolves each of an operation's own hard negatives is adjacent to it -------------------------------------------------------------------------
const reg = require(REGISTRY);
const adjacency = {};
for (const def of Object.values(reg.ASK_OPERATION_DEFINITIONS)) {
  if (!def.messageRoutable || def.safetyClass.endsWith('_BOUNDARY') || def.operationId === 'GROUNDED_GUIDANCE') continue;
  const via = {};
  for (const example of def.semantic.hardNegativeExamples ?? []) { const other = reg.resolveAskOperation(example).operationId; if (other !== def.operationId && other !== 'GROUNDED_GUIDANCE') (via[other] ??= []).push(example); }
  adjacency[def.operationId] = Object.fromEntries(Object.entries(via).sort(([a], [b]) => a.localeCompare(b)).map(([op, ex]) => [op, ex.slice(0, 3)]));
}

const header = '// GENERATED by scripts/ask-fast-path-rules.js. Do not edit. Regenerate with: node scripts/ask-fast-path-rules.js --write\n';
const rulesTs = `${header}export interface FastPathRuleManifestEntry { readonly id: string; readonly operationId: string; readonly confidence: number; readonly order: number; readonly hash: string; readonly condition: string; readonly references: readonly string[] }\nexport const FAST_PATH_RULE_MANIFEST: readonly FastPathRuleManifestEntry[] = ${JSON.stringify(rules_, null, 1)};\n`;
const adjTs = `${header}/** Operation-owned semantic adjacency (FR-FAST-9): for each operation, the other operations that resolve its own hard-negative examples, with up to three of those examples. */\nexport const FAST_PATH_ADJACENCY: Readonly<Record<string, Readonly<Record<string, readonly string[]>>>> = ${JSON.stringify(adjacency, null, 1)};\n`;
if (write) { fs.writeFileSync(OUT_RULES, rulesTs); fs.writeFileSync(OUT_ADJ, adjTs); console.log(`wrote ${rules_.length} rules (${edits.length} new ids), adjacency for ${Object.keys(adjacency).length} operations`); }
else {
  const stale = [[OUT_RULES, rulesTs], [OUT_ADJ, adjTs]].filter(([f, t]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== t);
  if (stale.length) { console.error(`out of date: ${stale.map(([f]) => path.basename(f)).join(', ')}; run node scripts/ask-fast-path-rules.js --write`); process.exit(1); }
  console.log('fast-path rule manifests are current');
}
