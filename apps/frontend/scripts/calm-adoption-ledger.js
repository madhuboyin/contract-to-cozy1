#!/usr/bin/env node
/* eslint-disable no-console */
// Consolidated plan Phase 0 / Phase 5: a generated Calm adoption ledger.
//
// Reads the block patterns the backend actually emits (the `type: 'X', id: 'y'` literals in apps/backend/src/services/ask) and the ids the frontend's
// isCalmAdopter recognises (apps/frontend/src/features/ask/calmAnswers.ts), and writes which emitted artifact blocks are adopted and which are not.
// Counts come from this output, never from prose. Run from the repo root or apps/frontend:
//   node apps/frontend/scripts/calm-adoption-ledger.js            # writes docs/architecture/ASK_COZY_CALM_ADOPTION_LEDGER.md
//   node apps/frontend/scripts/calm-adoption-ledger.js --check    # exits 1 if the committed ledger is stale
const fs = require('node:fs');
const path = require('node:path');

const repoRoot = path.resolve(__dirname, '..', '..', '..');
const backendDir = path.join(repoRoot, 'apps', 'backend', 'src', 'services', 'ask');
const calmFile = path.join(repoRoot, 'apps', 'frontend', 'src', 'features', 'ask', 'calmAnswers.ts');
const outFile = path.join(repoRoot, 'docs', 'architecture', 'ASK_COZY_CALM_ADOPTION_LEDGER.md');

// The blocks that can be an answer's one dominant artifact. SUMMARY, EVIDENCE and similar framing blocks are not artifacts.
const ARTIFACT_TYPES = new Set(['GROUPED_LIST', 'PRIORITY_LIST', 'TABLE', 'ENVIRONMENT_REPORT', 'CAPABILITY_LIST', 'TIMELINE', 'CHART', 'COMPARISON']);

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === '__tests__' ? [] : walk(full);
    return /\.ts$/.test(entry.name) ? [full] : [];
  });
}

function allIdLiterals() {
  const ids = new Set();
  for (const file of walk(backendDir)) for (const match of fs.readFileSync(file, 'utf8').matchAll(/\bid:\s*'([a-z0-9-]+)'/g)) ids.add(match[1]);
  return ids;
}

function emittedBlocks() {
  const found = new Map();
  // Both literal orders are used in the handlers: `type: 'X', id: 'y'` and `id: 'y', type: 'X'`.
  const patterns = [
    { regex: /type:\s*'([A-Z_]+)',\s*id:\s*'([a-z0-9-]+)'/g, typeAt: 1, idAt: 2 },
    { regex: /id:\s*'([a-z0-9-]+)',\s*type:\s*'([A-Z_]+)'/g, typeAt: 2, idAt: 1 },
  ];
  for (const file of walk(backendDir)) {
    const source = fs.readFileSync(file, 'utf8');
    for (const { regex, typeAt, idAt } of patterns) {
      let match;
      while ((match = regex.exec(source))) {
        if (!ARTIFACT_TYPES.has(match[typeAt])) continue;
        const key = `${match[typeAt]}:${match[idAt]}`;
        const files = found.get(key) ?? new Set();
        files.add(path.relative(repoRoot, file));
        found.set(key, files);
      }
    }
  }
  return found;
}

function adoptedIds() {
  const source = fs.readFileSync(calmFile, 'utf8');
  const body = source.slice(source.indexOf('export function isCalmAdopter'));
  return new Set([...body.matchAll(/'([a-z0-9]+(?:-[a-z0-9]+)+)'/g)].map((match) => match[1]).concat(/block\.type === 'ENVIRONMENT_REPORT'/.test(body) ? ['ENVIRONMENT_REPORT'] : []));
}

function build() {
  const emitted = emittedBlocks();
  const adopted = adoptedIds();
  const rows = [...emitted.entries()].map(([key, files]) => {
    const [type, id] = key.split(':');
    return { type, id, files: [...files].sort(), adopted: adopted.has(id) || (type === 'ENVIRONMENT_REPORT' && adopted.has('ENVIRONMENT_REPORT')) };
  }).sort((a, b) => a.type.localeCompare(b.type) || a.id.localeCompare(b.id));
  const total = rows.length;
  const done = rows.filter((row) => row.adopted).length;
  // An id the adopter names that no literal emission matched (a computed id, or an id since renamed) is listed so the gap is visible, not silently dropped.
  const literals = allIdLiterals();
  const unmatched = [...adopted].filter((id) => id !== 'ENVIRONMENT_REPORT' && !literals.has(id)).sort();
  const adoptedCount = adopted.size;
  const lines = [
    '# Ask Cozy Calm Adoption Ledger',
    '',
    '_Generated by `apps/frontend/scripts/calm-adoption-ledger.js`. Do not edit by hand; rerun the script._',
    '',
    `Ids recognised by \`isCalmAdopter\`: **${adoptedCount}** (${adoptedCount - unmatched.length} found as an \`id\` literal in the handlers).`,
    `Artifact blocks emitted with an adjacent \`type\`/\`id\` literal pair: **${total}**, of which **${done}** are adopted and **${total - done}** are not.`,
    '',
    'A block whose \`type\` is declared apart from its \`id\` is not in the table below; the adopted ids above are checked separately.',
    '',
    '| Type | Block id | Adopted | Emitted from |',
    '|---|---|---|---|',
    ...rows.map((row) => `| ${row.type} | \`${row.id}\` | ${row.adopted ? 'yes' : 'no'} | ${row.files.map((file) => `\`${file.replace('apps/backend/src/services/ask/', '')}\``).join(', ')} |`),
    '',
    ...(unmatched.length ? ['## Adopted ids with no `id` literal found', '', 'These ids are named by `isCalmAdopter` but no `id: \'...\'` literal for them was found in the handlers (the id may be computed or renamed). Verify each by hand.', '', ...unmatched.map((id) => `- \`${id}\``), ''] : []),
  ];
  return lines.join('\n');
}

const next = build();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (current !== next) { console.error('The Calm adoption ledger is stale. Run: node apps/frontend/scripts/calm-adoption-ledger.js'); process.exit(1); }
  console.log('The Calm adoption ledger is current.');
} else {
  fs.writeFileSync(outFile, next);
  console.log(`Wrote ${path.relative(repoRoot, outFile)}`);
}
